import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const schema = await readFile(new URL('supabase/schema.sql', root), 'utf8')
const document = JSON.parse(await readFile(new URL('src/data/default-ceremony.json', root), 'utf8'))
const json = JSON.stringify(document)
if (json.includes('$ceremony$')) throw Error('Seed delimiter appears in the content.')
const seed = `-- Original ceremony, inserted once. Existing published edits are preserved.\ninsert into public.wedding_ceremony (id, document)\nvalues ('mohini-jewel', $ceremony$${json}$ceremony$::jsonb)\non conflict (id) do nothing;\n\nnotify pgrst, 'reload schema';\n`
await writeFile(new URL('supabase/seed.sql', root), seed)
await writeFile(new URL('supabase/setup.sql', root), '-- MOHINI & JEWEL: paste this entire file into Supabase SQL Editor and click Run.\n-- Generated by npm run seed; source: schema.sql and default-ceremony.json.\n\n' + schema + '\n' + seed)
console.log(`Generated supabase/setup.sql with ${document.sections.length} ceremony sections.`)
